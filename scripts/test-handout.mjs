var DEG = Math.PI / 180;
var RAD = 180 / Math.PI;
function clamp1(x) {
  return Math.max(-1, Math.min(1, x));
}
function angularSeparation(lon1, lat1, lon2, lat2) {
  const dlat = (lat2 - lat1) * DEG;
  let dlon = ((lon2 - lon1 + 540) % 360 - 180) * DEG;
  const s1 = Math.sin(dlat / 2);
  const s2 = Math.sin(dlon / 2);
  const a = s1 * s1 + Math.cos(lat1 * DEG) * Math.cos(lat2 * DEG) * s2 * s2;
  return 2 * Math.asin(clamp1(Math.sqrt(a))) * RAD;
}
function destinationPoint(lon0, lat0, bearing, distance) {
  const \u03B4 = distance * DEG;
  const \u03B8 = bearing * DEG;
  const \u03C61 = lat0 * DEG;
  const \u03BB1 = lon0 * DEG;
  const sin\u03C62 = Math.sin(\u03C61) * Math.cos(\u03B4) + Math.cos(\u03C61) * Math.sin(\u03B4) * Math.cos(\u03B8);
  const \u03C62 = Math.asin(clamp1(sin\u03C62));
  const y = Math.sin(\u03B8) * Math.sin(\u03B4) * Math.cos(\u03C61);
  const x = Math.cos(\u03B4) - Math.sin(\u03C61) * sin\u03C62;
  const \u03BB2 = \u03BB1 + Math.atan2(y, x);
  const lon = (\u03BB2 * RAD % 360 + 360) % 360;
  return [lon, \u03C62 * RAD];
}
